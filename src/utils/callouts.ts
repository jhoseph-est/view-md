export function renderCallouts() {
  const blockquotes = document.querySelectorAll<HTMLQuoteElement>('.main-content blockquote');
  blockquotes.forEach((bq) => {
    if (bq.dataset.calloutProcessed === 'true') return;
    const firstP = bq.querySelector('p');
    if (!firstP) return;
    const firstLine = firstP.innerHTML.trim();
    const match = firstLine.match(/^\[!([a-zA-Z0-9_-]+)\](?:\s*(.*))?$/m);
    if (match) {
      const type = match[1].toLowerCase();
      const customTitle = match[2] ? match[2].trim() : type.charAt(0).toUpperCase() + type.slice(1);
      const iconSVG = CALLOUT_ICONS[type] || CALLOUT_ICONS.note;
      
      bq.setAttribute('data-callout', type);
      bq.classList.add(`callout-${type}`);
      bq.dataset.calloutProcessed = 'true';
      
      const titleEl = document.createElement('div');
      titleEl.className = 'callout-title';
      titleEl.innerHTML = `
        <span class="callout-title-icon">${iconSVG}</span>
        <span class="callout-title-text">${customTitle}</span>
      `;
      
      const remainingHTML = firstP.innerHTML.replace(/^\[![a-zA-Z0-9_-]+\](?:\s*.*)?$/m, '').trim();
      if (remainingHTML) {
        firstP.innerHTML = remainingHTML;
      } else {
        firstP.remove();
      }
      bq.insertBefore(titleEl, bq.firstChild);
    }
  });
}